/**
 * Limits over a real source database, on each engine: a composed server over
 * a fresh database whose tables carry `table.capacity` as stored overrides,
 * public endpoints made the way an app's install makes them, and the write
 * service handed a target the way a staff route hands one.
 *
 * `poolMax` (or `ADMINIUM_TEST_SOURCE_POOL_MAX`, which the test task passes
 * through) sets the source pool's size: a guard that checks out a second
 * connection inside its transaction stalls a pool of one.
 *
 * Postgres and MySQL gate on TEST_POSTGRES_URL / TEST_MYSQL_URL (`''` counts
 * as absent).
 */
