/**
 * A ROW TAKES A RESOURCE FOR A TIME (`table.occupies`).
 *
 * A showroom space booked from two to three is not booked again at half
 * past two; a crew is not sent out on a weekday it does not work. That is
 * all the rule says: a resource, a time, and — if the app keeps them — the
 * hours the resource works. Nothing of what booking people asks.
 *
 * Every write below goes through the data routes of the composed server, on
 * each engine, against a real source database that carries the rule as an
 * override. The connection keeps UTC, so the times read as written.
 */
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { overridesRepo, snapshotsRepo } from '@adminium/meta';

import { runIntrospection } from '../src/connections/introspect.js';
import { ENGINES, world, type World } from './row-limit-world.js';

// Monday 17 August 2026 and the days after it.
const MON = '2026-08-17';
const TUE = '2026-08-18';
const SUN = '2026-08-23';

for (const [dialect, available] of ENGINES) {
  describe.skipIf(!available)(`a row takes a resource for a time [${dialect}]`, () => {
    let w: World;
    const ids = new Map<string, string>();
    const id = (table: string): string => ids.get(table)!;
    type Reply = { statusCode: number; body: string };
    const call = (method: 'POST' | 'PATCH', path: string, values: Record<string, unknown>): Promise<Reply> =>
      w.app.inject({ method, url: `/api/v1/data/${w.connectionId}/${path}`, headers: { cookie: w.owner.cookie }, payload: { values } });
    /** Why a write was refused: a 409's code, or the reason a 422 carries. */
    const code = (res: Reply): unknown => {
      const error = (JSON.parse(res.body) as { error?: { code?: unknown; details?: { reason?: unknown } } }).error;
      return error?.details?.reason ?? error?.code;
    };
    const made = (res: Reply): number => Number((JSON.parse(res.body) as { data: { id: number } }).data.id);
    const book = (space: number, at: string, minutes: number, state = 'confirmed'): Promise<Reply> =>
      call('POST', id('space_bookings'), { space_id: space, starts_at: `${at}:00Z`, minutes, state });

    beforeAll(async () => {
      w = await world(dialect);
      const key = dialect === 'postgres' ? 'integer generated by default as identity primary key' : dialect === 'mysql' ? 'int auto_increment primary key' : 'integer primary key';
      const at = dialect === 'postgres' ? 'timestamptz' : dialect === 'mysql' ? 'datetime' : 'timestamp';
      for (const statement of [
        `create table spaces (id ${key}, name varchar(40) not null)`,
        `create table space_days (id ${key}, space_id integer not null, weekday varchar(3) not null, opens varchar(5) not null, closes varchar(5) not null)`,
        `create table space_bookings (id ${key}, space_id integer, starts_at ${at}, minutes integer not null default 60, state varchar(16) not null default 'tentative')`,
        `create table crew_days (id ${key}, crew_id integer not null, weekday varchar(3) not null)`,
        `create table crew_visits (id ${key}, crew_id integer, day date, state varchar(16) not null default 'planned')`,
        `create table loans (id ${key}, item varchar(20) not null, from_at ${at} not null, to_at ${at} not null)`,
        `create table demo_days (id ${key}, van varchar(20) not null, day date not null)`,
        `insert into spaces (name) values ('Kitchen bay'), ('Bathroom bay')`,
        // The kitchen bay opens Monday to Friday, nine to five; the bathroom bay keeps no hours at all.
        ...['mon', 'tue', 'wed', 'thu', 'fri'].map((weekday) => `insert into space_days (space_id, weekday, opens, closes) values (1, '${weekday}', '09:00', '17:00')`),
        // Crew one works Monday to Friday.
        ...['mon', 'tue', 'wed', 'thu', 'fri'].map((weekday) => `insert into crew_days (crew_id, weekday) values (1, '${weekday}')`),
      ]) {
        await w.run(statement);
      }
      await w.meta.db.updateTable('adminium_connections').set({ timezone: 'UTC' }).where('id', '=', w.connectionId).execute();
      await runIntrospection({ manager: w.manager, meta: w.meta, connectionId: w.connectionId });
      const tables = ((await snapshotsRepo(w.meta).latest(w.connectionId))!.schema as { tables: { id: string; name: string }[] }).tables;
      for (const table of tables) ids.set(table.name, table.id);
      const overrides = overridesRepo(w.meta);
      const rule = (table: string, value: Record<string, unknown>) => overrides.create({ connectionId: w.connectionId, op: 'table.occupies', tableName: id(table), value, origin: 'user' });
      await rule('space_bookings', {
        resource: 'space_id',
        start: 'starts_at',
        minutes: 'minutes',
        countWhere: { column: 'state', values: ['tentative', 'confirmed'] },
      });
      await rule('crew_visits', { resource: 'crew_id', day: 'day', shared: true, countWhere: { column: 'state', values: ['planned', 'booked'] }, hours: { table: id('crew_days'), resource: 'crew_id', weekday: 'weekday' } });
      await rule('loans', { resource: 'item', start: 'from_at', end: 'to_at' });
      await rule('demo_days', { resource: 'van', day: 'day' });
    }, 120_000);
    afterAll(async () => {
      await w?.close();
    });

    describe('a space and a time', () => {
      it('is taken once: an overlapping row is refused, one that only touches it is not', async () => {
        const first = await book(2, `${MON}T14:00`, 60);
        expect(first.statusCode, first.body).toBe(201);
        // Half past two, inside it; and one that starts before and runs into it.
        expect(code(await book(2, `${MON}T14:30`, 30))).toBe('BOOKING_TAKEN');
        expect(code(await book(2, `${MON}T13:30`, 45))).toBe('BOOKING_TAKEN');
        // Three o'clock starts as the first ends; one o'clock ends as it starts.
        expect((await book(2, `${MON}T15:00`, 60)).statusCode).toBe(201);
        expect((await book(2, `${MON}T13:00`, 60)).statusCode).toBe(201);
        // The other space is free all along.
        expect((await book(1, `${MON}T14:00`, 60)).statusCode).toBe(201);
      });

      it('is free again when the row stops counting, and held again when it counts once more', async () => {
        const held = await book(2, `${TUE}T10:00`, 60, 'tentative');
        expect(code(await book(2, `${TUE}T10:15`, 30))).toBe('BOOKING_TAKEN');
        expect((await call('PATCH', `${id('space_bookings')}/${made(held)}`, { state: 'cancelled' })).statusCode).toBe(200);
        const second = await book(2, `${TUE}T10:15`, 30);
        expect(second.statusCode, second.body).toBe(201);
        // The cancelled one cannot come back over the row that took its time.
        expect(code(await call('PATCH', `${id('space_bookings')}/${made(held)}`, { state: 'confirmed' }))).toBe('BOOKING_TAKEN');
      });

      it('moves and grows without blocking itself, and not onto another row', async () => {
        const mine = await book(2, `${TUE}T12:00`, 60);
        const theirs = await book(2, `${TUE}T14:00`, 60);
        expect(theirs.statusCode).toBe(201);
        const path = `${id('space_bookings')}/${made(mine)}`;
        // Half an hour later still overlaps its own old time: that is no clash.
        expect((await call('PATCH', path, { starts_at: `${TUE}T12:30:00Z` })).statusCode).toBe(200);
        // Longer, into two o'clock: refused. A change that places nothing is never judged.
        expect(code(await call('PATCH', path, { minutes: 120 }))).toBe('BOOKING_TAKEN');
        expect((await call('PATCH', path, { minutes: 90 })).statusCode).toBe(200);
        // To the other space at a time that is taken there (Monday at two), and to one that is not.
        expect(code(await call('PATCH', path, { space_id: 1, starts_at: `${MON}T14:30:00Z` }))).toBe('BOOKING_TAKEN');
        expect((await call('PATCH', path, { space_id: 1, starts_at: `${MON}T16:00:00Z`, minutes: 30 })).statusCode).toBe(200);
      });

      it('judges nothing while the row has no space or no time yet', async () => {
        expect((await call('POST', id('space_bookings'), { starts_at: `${MON}T14:00:00Z`, minutes: 60, state: 'confirmed' })).statusCode).toBe(201);
        const waiting = await call('POST', id('space_bookings'), { space_id: 2, minutes: 60, state: 'confirmed' });
        expect(waiting.statusCode, waiting.body).toBe(201);
        // Given its time, it is judged like any other.
        expect(code(await call('PATCH', `${id('space_bookings')}/${made(waiting)}`, { starts_at: `${MON}T14:10:00Z` }))).toBe('BOOKING_TAKEN');
      });
    });

    describe('a start and an end', () => {
      it('holds the thing from one to the other, over midnight too', async () => {
        const loan = (from: string, to: string) => call('POST', id('loans'), { item: 'sample case', from_at: `${from}:00Z`, to_at: `${to}:00Z` });
        const out = await loan(`${MON}T16:00`, `${TUE}T10:00`);
        expect(out.statusCode, out.body).toBe(201);
        // The next morning it is still out.
        expect(code(await loan(`${TUE}T09:00`, `${TUE}T12:00`))).toBe('BOOKING_TAKEN');
        expect((await loan(`${TUE}T10:00`, `${TUE}T12:00`)).statusCode).toBe(201);
        // An end before its start, and a loan longer than a row may last.
        expect(code(await loan(`${TUE}T15:00`, `${TUE}T14:00`))).toBe('BOOKING_OUT_OF_RANGE');
        expect(code(await loan('2026-09-01T09:00', '2026-10-15T09:00'))).toBe('BOOKING_OUT_OF_RANGE');
      });
    });

    describe('a whole day', () => {
      it('is one row a day for each thing', async () => {
        const day = (van: string, on: string) => call('POST', id('demo_days'), { van, day: on });
        const first = await day('Van A', MON);
        expect(first.statusCode, first.body).toBe(201);
        expect(code(await day('Van A', MON))).toBe('BOOKING_TAKEN');
        expect((await day('Van B', MON)).statusCode).toBe(201);
        expect((await day('Van A', TUE)).statusCode).toBe(201);
        // Its own day again is no clash; another row's day is.
        expect((await call('PATCH', `${id('demo_days')}/${made(first)}`, { day: MON })).statusCode).toBe(200);
        expect(code(await call('PATCH', `${id('demo_days')}/${made(first)}`, { day: TUE }))).toBe('BOOKING_TAKEN');
      });
    });

    describe('the hours a resource works', () => {
      it('lets a crew take several visits on a day it works, and none on its day off', async () => {
        const visit = (crew: number | null, on: string) => call('POST', id('crew_visits'), { crew_id: crew, day: on });
        const one = await visit(1, MON);
        expect(one.statusCode, one.body).toBe(201);
        // The rows share the day: a second visit on Monday is the crew's own business.
        expect((await visit(1, MON)).statusCode).toBe(201);
        expect(code(await visit(1, SUN))).toBe('BOOKING_CLOSED');
        // Moved onto the Sunday: refused. A crew with no week written down keeps none, and is held to none.
        expect(code(await call('PATCH', `${id('crew_visits')}/${made(one)}`, { day: SUN }))).toBe('BOOKING_CLOSED');
        expect((await visit(2, SUN)).statusCode).toBe(201);
        // No crew yet: nothing to judge.
        expect((await visit(null, SUN)).statusCode).toBe(201);
        // A visit left waiting on the Sunday takes nothing; booked there, it is refused like a new one.
        const waiting = await call('POST', id('crew_visits'), { crew_id: 1, day: SUN, state: 'waiting' });
        expect(waiting.statusCode, waiting.body).toBe(201);
        expect(code(await call('PATCH', `${id('crew_visits')}/${made(waiting)}`, { state: 'booked' }))).toBe('BOOKING_CLOSED');
        expect((await call('PATCH', `${id('crew_visits')}/${made(waiting)}`, { state: 'booked', day: TUE })).statusCode).toBe(200);
      });

      it('holds a timed row inside the opening and the closing time', async () => {
        const overrides = overridesRepo(w.meta);
        await w.meta.db.deleteFrom('adminium_schema_overrides').where('connectionId', '=', w.connectionId).where('op', '=', 'table.occupies' as never).where('tableName', '=', id('space_bookings')).execute();
        await overrides.create({
          connectionId: w.connectionId,
          op: 'table.occupies',
          tableName: id('space_bookings'),
          value: { resource: 'space_id', start: 'starts_at', minutes: 'minutes', countWhere: { column: 'state', values: ['tentative', 'confirmed'] }, hours: { table: id('space_days'), resource: 'space_id', weekday: 'weekday', opens: 'opens', closes: 'closes' } },
          origin: 'user',
        });
        const wed = '2026-08-19';
        expect((await book(1, `${wed}T09:00`, 60)).statusCode).toBe(201);
        const last = await book(1, `${wed}T16:00`, 60);
        expect(last.statusCode, last.body).toBe(201);
        // Before it opens, past its close, and on a day it keeps no hours for.
        expect(code(await book(1, `${wed}T08:30`, 60))).toBe('BOOKING_OUT_OF_HOURS');
        expect(code(await book(1, `${wed}T16:30`, 60))).toBe('BOOKING_OUT_OF_HOURS');
        expect(code(await book(1, `${SUN}T10:00`, 60))).toBe('BOOKING_CLOSED');
        // Inside the hours the overlap still holds.
        expect(code(await book(1, `${wed}T09:30`, 30))).toBe('BOOKING_TAKEN');
      });
    });
  });
}
