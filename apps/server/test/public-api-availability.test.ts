/**
 * A guest's booking, end to end over the public API, on every engine: which
 * times of a day have room, the booking itself, the slot filling up, a claimed
 * guest changing theirs, and cancelling too late.
 *
 * Nothing is faked below the HTTP route: a real source database carries the
 * booking limit as an override, the key is made from endpoints the way an
 * app's install makes them, and every answer comes from the composed server.
 */
