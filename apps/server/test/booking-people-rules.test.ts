describe('time away across a change of the clocks', () => {
  it('counts both sides of the hour the clocks repeat', () => {
    const zone = 'America/New_York';
    const minuteOf = (moment: number) => venueClock(new Date(moment), zone).minute;
    // 01:30 EDT to 01:15 EST on 1 November: 45 minutes, the wall clock reading 01:30–02:00, then 01:00–01:15.
    const start = Date.parse('2026-11-01T05:30:00Z');
    const end = Date.parse('2026-11-01T06:15:00Z');
    expect(wallSpans(start, end, minuteOf)).toEqual([{ start: 90, end: 120 }, { start: 60, end: 75 }]);
    expect(minutesLeft({ opens: 60, closes: 180 }, wallSpans(start, end, minuteOf))).toBe(75);
    expect(wallSpans(Date.parse('2026-11-02T15:00:00Z'), Date.parse('2026-11-02T16:00:00Z'), minuteOf)).toEqual([{ start: 600, end: 660 }]);
  });
});

describe('a strip of days', () => {
  it('reads its days once, whatever its length', async () => {
    const p = await serving('sqlite');
    await p.away(NOOR, at(FRI, '13:00'), at(FRI, '17:00'));
    await p.seed(ELIN, FACIAL, WED, '10:00');
    const { rule, target } = await p.target();
    let statements = 0;
    const database = new BetterSqlite3(p.file);
    const counted = new Kysely<SourceDatabase>({ dialect: new SqliteDialect({ database }), log: (event) => { if (event.level === 'query') statements += 1; } });
    const input = { kind: FACIAL, resource: 'any', isPublic: true, excludePk: null, now: new Date() };
    const measure = async (days: number) => {
      statements = 0;
      const rows = await bookingDays(rule, { ...target, db: counted }, WED, days, 60, input);
      expect(rows).toHaveLength(days);
      return statements;
    };
    const short = await measure(2);
    const long = await measure(31);
    await counted.destroy();
    expect(long).toBe(short);
    expect(long).toBeLessThanOrEqual(14);
  });
});
