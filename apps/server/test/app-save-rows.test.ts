/**
 * ROWS SAVED WITH THE TABLES, AND WRITTEN AGAIN ON THE TARGET.
 *
 * Starting rows keep their ids, and the target's next row takes a key past
 * them. Over 200 starting rows, a saved view picks which; without one, the
 * first 200 travel and Check says so. Parents go first; rows that point at
 * each other through links that may be empty are linked once both are in;
 * rows that need each other through links that cannot be empty are a choice.
 * A personal column, or one whose name looks like a secret, stays behind
 * unless ticked; a row whose parent stays behind is named, never dropped in
 * silence. A staff member in a sample row is a sample person, never an id.
 *
 * SQLite always runs; Postgres runs with TEST_POSTGRES_URL, MySQL with
 * TEST_MYSQL_URL (`./app-install-harness.ts`).
 */
import { sampleBundleIssues, sampleBundleSchema, validateManifest, type Manifest } from '@adminium/manifest';
import { pagesRepo, viewsRepo } from '@adminium/meta';
import { afterEach, describe, expect, it } from 'vitest';

import { findSampleApp } from '../src/apps/sample-data.js';
import { ENGINES, installHarness, type Dialect, type Harness, type HarnessOptions } from './app-install-harness.js';
import { asFile, made, override, save, tableId } from './app-save-source.js';

type Doc = Record<string, unknown>;

let open: Harness[] = [];
afterEach(async () => {
  for (const h of open) await h.close();
  open = [];
});

async function harness(dialect: Dialect, options: HarnessOptions = {}): Promise<Harness> {
  const h = await installHarness(dialect, options);
  open.push(h);
  return h;
}

/** A counting key, as each engine spells it. */
const counting = (dialect: Dialect): string =>
  dialect === 'postgres' ? 'id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' : dialect === 'mysql' ? 'id int AUTO_INCREMENT PRIMARY KEY' : 'id integer PRIMARY KEY';

/** A link added after both tables are there, where the engine can add one. */
function laterLink(dialect: Dialect, table: string, column: string, to: string): string[] {
  return dialect === 'sqlite' ? [] : [`ALTER TABLE ${table} ADD CONSTRAINT ${table}_${column}_fk FOREIGN KEY (${column}) REFERENCES ${to} (id)`];
}

const seedRows = (files: Record<string, string>, ref: string): Doc[] => JSON.parse(files[`seeds/start-${ref}.json`]!) as Doc[];
const ids = (rows: Record<string, unknown>[], column = 'id'): number[] => rows.map((row) => Number(row[column]));

for (const [dialect, available] of ENGINES) {
  describe.skipIf(!available)(`saving rows — ${dialect}`, () => {
    it('keeps starting rows\' ids, and the target\'s next row takes a key past them', async () => {
      const h = await harness(dialect);
      await made(h, [
        `CREATE TABLE customers (${counting(dialect)}, name varchar(80) NOT NULL)`,
        `CREATE TABLE orders (${counting(dialect)}, customer_id integer NOT NULL, total decimal(10,2) NOT NULL, CONSTRAINT orders_customer FOREIGN KEY (customer_id) REFERENCES customers (id))`,
        `INSERT INTO customers (id, name) VALUES (1, 'Ann'), (2, 'Bo'), (7, 'Cy')`,
        `INSERT INTO orders (id, customer_id, total) VALUES (3, 7, 12.5), (4, 1, 3)`,
      ]);
      const customers = await tableId(h, 'customers');
      const orders = await tableId(h, 'orders');
      const saved = await save(h, dialect, { rows: { [orders]: { mode: 'starting' }, [customers]: { mode: 'starting' } } }, true);
      const { manifest, files } = asFile(saved);
      expect(validateManifest(manifest, { allowLocalPublisher: true }).ok).toBe(true);
      // Parents first, whatever order they were chosen in.
      expect(manifest['seeds']).toEqual([
        { table: 'customers', file: 'seeds/start-customers.json' },
        { table: 'orders', file: 'seeds/start-orders.json' },
      ]);
      expect(seedRows(files, 'orders')).toEqual([
        { id: 3, customer_id: 7, total: 12.5 },
        { id: 4, customer_id: 1, total: 3 },
      ]);

      const target = await harness(dialect);
      const installed = await target.install(manifest, {}, files);
      expect(installed.statusCode, installed.body).toBe(200);
      expect(ids(await target.rows('SELECT id FROM customers ORDER BY id'))).toEqual([1, 2, 7]);
      expect(await target.rows('SELECT id, customer_id FROM orders ORDER BY id')).toEqual([
        { id: 3, customer_id: 7 },
        { id: 4, customer_id: 1 },
      ]);
      // The next customer is the owner's: a key no starting row holds.
      await target.run(`INSERT INTO customers (name) VALUES ('Di')`);
      const [di] = await target.rows(`SELECT id FROM customers WHERE name = 'Di'`);
      expect(Number(di!['id'])).toBeGreaterThan(7);
    });

    it('picks 200 starting rows by a saved view, and says so when no view picks them', async () => {
      const h = await harness(dialect);
      const values = Array.from({ length: 250 }, (_v, i) => `(${String(i + 1)}, ${String(i + 1)})`);
      await made(h, [`CREATE TABLE items (${counting(dialect)}, n integer NOT NULL)`, `INSERT INTO items (id, n) VALUES ${values.join(', ')}`]);
      const items = await tableId(h, 'items');
      const page = await pagesRepo(h.meta).create({ connectionId: h.connectionId, slug: 'items', type: 'page-crud', title: 'Items', config: { v: 1, kind: 'page', template: 'page-crud', source: { connectionId: h.connectionId, table: items } } });
      const view = await viewsRepo(h.meta).create({ pageId: page.id, userId: null, name: 'Big ones', config: { v: 1, filters: [{ column: 'n', op: 'gte', value: 30 }], sort: { column: 'n', dir: 'desc' } } });

      const byView = await save(h, dialect, { rows: { [items]: { mode: 'starting', viewId: view.id } } }, true);
      const picked = seedRows(asFile(byView).files, 'items');
      expect(picked).toHaveLength(200);
      expect(picked[0]).toEqual({ id: 250, n: 250 });
      expect(picked.at(-1)).toEqual({ id: 51, n: 51 });
      expect(byView.check.some((item) => item.code === 'ROWS_FIRST')).toBe(false);

      const first = await save(h, dialect, { rows: { [items]: { mode: 'starting' } } }, true);
      expect(ids(seedRows(asFile(first).files, 'items'))).toEqual(Array.from({ length: 200 }, (_v, i) => i + 1));
      expect(first.check).toContainEqual(expect.objectContaining({ group: 'info', code: 'ROWS_FIRST', item: 'items' }));
    });

    it('writes parents first, and links rows that point at each other once both are in', async () => {
      const h = await harness(dialect);
      await made(h, [
        `CREATE TABLE teams (id integer PRIMARY KEY, name varchar(40) NOT NULL, captain_id integer${dialect === 'sqlite' ? ' REFERENCES people (id)' : ''})`,
        `CREATE TABLE people (id integer PRIMARY KEY, name varchar(40) NOT NULL, team_id integer NOT NULL, mentor_id integer, CONSTRAINT people_team FOREIGN KEY (team_id) REFERENCES teams (id), CONSTRAINT people_mentor FOREIGN KEY (mentor_id) REFERENCES people (id))`,
        ...laterLink(dialect, 'teams', 'captain_id', 'people'),
        `INSERT INTO teams (id, name) VALUES (1, 'Red'), (2, 'Blue')`,
        `INSERT INTO people (id, name, team_id, mentor_id) VALUES (1, 'Ann', 1, NULL), (2, 'Bo', 1, 1), (3, 'Cy', 2, NULL), (5, 'Ed', 2, NULL)`,
        `INSERT INTO people (id, name, team_id, mentor_id) VALUES (4, 'Di', 2, 5)`,
        `UPDATE people SET mentor_id = 2 WHERE id = 1`,
        `UPDATE teams SET captain_id = 2 WHERE id = 1`,
      ]);
      const teams = await tableId(h, 'teams');
      const people = await tableId(h, 'people');
      const saved = await save(h, dialect, { rows: { [people]: { mode: 'starting' }, [teams]: { mode: 'starting' } } }, true);
      expect(saved.check.filter((item) => item.group === 'choice' && item.code !== 'NO_PAGE')).toEqual([]);
      const { manifest, files } = asFile(saved);
      expect((manifest['seeds'] as { table: string }[]).map((seed) => seed.table)).toEqual(['teams', 'people']);
      // A team names its captain, who comes later, by the label the install fills the link from.
      expect(seedRows(files, 'teams')).toEqual([
        { id: 1, name: 'Red', captain_id: { '@ref': 'people.2' } },
        { id: 2, name: 'Blue', captain_id: null },
      ]);
      // A mentor before the person they mentor; the two who mentor each other, linked in the second pass.
      expect(seedRows(files, 'people').map((row) => [row['id'], row['mentor_id'], row['@label'] ?? null])).toEqual([
        [3, null, null],
        [5, null, null],
        [4, 5, null],
        [1, { '@ref': 'people.2' }, null],
        [2, 1, 'people.2'],
      ]);

      const target = await harness(dialect);
      const installed = await target.install(manifest, {}, files);
      expect(installed.statusCode, installed.body).toBe(200);
      expect(await target.rows('SELECT id, captain_id FROM teams ORDER BY id')).toEqual([
        { id: 1, captain_id: 2 },
        { id: 2, captain_id: null },
      ]);
      expect(await target.rows('SELECT id, mentor_id FROM people ORDER BY id')).toEqual([
        { id: 1, mentor_id: 2 },
        { id: 2, mentor_id: 1 },
        { id: 3, mentor_id: null },
        { id: 4, mentor_id: 5 },
        { id: 5, mentor_id: null },
      ]);
    });

    it('asks about rows that need each other through links that cannot be empty', async () => {
      const h = await harness(dialect);
      await made(h, [
        `CREATE TABLE nodes (id integer PRIMARY KEY, next_id integer NOT NULL${dialect === 'mysql' ? '' : ', CONSTRAINT nodes_next FOREIGN KEY (next_id) REFERENCES nodes (id)'})`,
        `INSERT INTO nodes (id, next_id) VALUES (1, 2), (2, 1)`,
        ...(dialect === 'mysql' ? laterLink(dialect, 'nodes', 'next_id', 'nodes') : []),
        `CREATE TABLE tags (id integer PRIMARY KEY, name varchar(20) NOT NULL)`,
        `INSERT INTO tags (id, name) VALUES (1, 'blue')`,
      ]);
      const nodes = await tableId(h, 'nodes');
      const tags = await tableId(h, 'tags');
      const asked = await save(h, dialect, { rows: { [nodes]: { mode: 'starting' }, [tags]: { mode: 'starting' } } }, true);
      expect(asked.check.filter((item) => item.group === 'choice' && item.code !== 'NO_PAGE')).toEqual([
        expect.objectContaining({ code: 'ROWS_REQUIRED_CYCLE', kind: 'rows', item: 'nodes', answer: { choices: ['leave-out'], target: `rows:${nodes}` } }),
      ]);
      expect(asked.manifest.seeds).toEqual([{ table: 'tags', file: 'seeds/start-tags.json' }]);

      const answered = await save(h, dialect, { rows: { [nodes]: { mode: 'starting' }, [tags]: { mode: 'starting' } }, leaveOut: [`rows:${nodes}`] }, true);
      expect(answered.check.filter((item) => item.group === 'choice' && item.code !== 'NO_PAGE')).toEqual([]);
      expect(answered.manifest.seeds).toEqual([{ table: 'tags', file: 'seeds/start-tags.json' }]);
    });
  });
}

describe('saving rows — what stays behind', () => {
  it('leaves personal and secret-looking values behind unless ticked, and names rows whose parent stays behind', async () => {
    const h = await harness('sqlite');
    await made(h, [
      `CREATE TABLE customers (id integer PRIMARY KEY, name varchar(80) NOT NULL, email varchar(120), api_token varchar(64))`,
      `CREATE TABLE orders (id integer PRIMARY KEY, customer_id integer NOT NULL REFERENCES customers (id), note text)`,
      `INSERT INTO customers (id, name, email, api_token) VALUES (1, 'Ann', 'ann@example.test', 'not-a-real-token-0001')`,
      `INSERT INTO orders (id, customer_id, note) VALUES (1, 1, 'first')`,
    ]);
    await override(h, 'customers', 'column.pii', { masked: true, kind: 'email' }, 'email', 'auto');
    const customers = await tableId(h, 'customers');
    const orders = await tableId(h, 'orders');

    const quiet = await save(h, 'sqlite', { rows: { [customers]: { mode: 'starting' } } }, true);
    const files = asFile(quiet).files;
    expect(seedRows(files, 'customers')).toEqual([{ id: 1, name: 'Ann', email: null, api_token: null }]);
    expect(JSON.stringify([...quiet.files.values()].map((bytes) => Buffer.from(bytes).toString()))).not.toContain('ann@example.test');
    expect(quiet.check).toContainEqual(expect.objectContaining({ group: 'info', code: 'ROWS_PERSONAL_EMPTY', item: 'customers', field: 'email' }));
    expect(quiet.check).toContainEqual(expect.objectContaining({ group: 'info', code: 'ROWS_PERSONAL_EMPTY', item: 'customers', field: 'api_token' }));

    const ticked = await save(h, 'sqlite', { rows: { [customers]: { mode: 'starting' } }, personalColumns: [`${customers}.email`] }, true);
    expect(seedRows(asFile(ticked).files, 'customers')).toEqual([{ id: 1, name: 'Ann', email: 'ann@example.test', api_token: null }]);

    // The orders' customers stay behind: the rows that need them do too, and Check says how many.
    const orphans = await save(h, 'sqlite', { rows: { [orders]: { mode: 'starting' } } }, true);
    expect(orphans.manifest.seeds).toBeUndefined();
    expect(orphans.check).toContainEqual(expect.objectContaining({ group: 'info', code: 'ROWS_PARENT_LEFT_OUT', item: 'orders', field: 'customer_id', message: expect.stringContaining('1 rows of "orders" stay behind') }));
  });

  it('writes sample rows the format accepts, a staff member as a sample person, and adds them on the target', async () => {
    const h = await harness('sqlite');
    await made(h, [
      `CREATE TABLE tasks (id integer PRIMARY KEY, title varchar(80) NOT NULL, owner varchar(40), done boolean NOT NULL DEFAULT 0)`,
      `INSERT INTO tasks (id, title, owner, done) VALUES (1, 'Paint', 'usr_owner_0001', 1), (2, 'Fix', 'usr_owner_0001', 0), (3, 'Sweep', NULL, 0)`,
    ]);
    await override(h, 'tasks', 'column.staff', { staff: true }, 'owner');
    const tasks = await tableId(h, 'tasks');
    const saved = await save(h, 'sqlite', { rows: { [tasks]: { mode: 'sample' } } }, true);
    const { manifest, files } = asFile(saved);
    expect(validateManifest(manifest, { allowLocalPublisher: true }).ok).toBe(true);
    expect(manifest['sampleData']).toEqual({ file: 'seeds/sample.json', people: [{ key: 'person-1', name: 'Sample person 1' }] });
    const bundle = sampleBundleSchema.parse(JSON.parse(files['seeds/sample.json']!));
    expect(sampleBundleIssues(bundle, manifest as unknown as Manifest)).toEqual([]);
    expect(bundle.tables).toEqual([
      {
        ref: 'tasks',
        rows: [
          { id: 1, title: 'Paint', owner: { '@person': 'person-1' }, done: true },
          { id: 2, title: 'Fix', owner: { '@person': 'person-1' }, done: false },
          { id: 3, title: 'Sweep', owner: null, done: false },
        ],
      },
    ]);
    expect(files['seeds/sample.json']).not.toContain('usr_owner_0001');

    const target = await harness('sqlite', { full: true });
    const installed = await target.install(manifest, {}, files);
    expect(installed.statusCode, installed.body).toBe(200);
    await target.samples!.add((await findSampleApp(target.meta, 'shop'))!, { locale: 'en-US', userId: null, userLabel: 'test' });
    const rows = await target.rows('SELECT id, title, owner FROM tasks ORDER BY id');
    expect(ids(rows)).toEqual([1, 2, 3]);
    expect(rows[0]!['owner']).not.toBe('usr_owner_0001');
    expect(rows[0]!['owner']).toBe(rows[1]!['owner']);
  });
});
