/**
 * SAVING A DATABASE'S TABLES INTO AN APP FILE, AND INSTALLING IT AGAIN.
 *
 * Tables made by hand, then changed the way a person changes them in
 * Adminium: a table and a column renamed in two languages, a link added in
 * Adminium, a column marked personal by the engine's own guess, a list of
 * answers. Saved, the file validates as a self-made app and holds no id;
 * installed on a fresh database, the tables are the same by introspection and
 * the person's words are there again. Installed back onto the database it was
 * saved from, using its tables, it plans no change at all.
 *
 * What has no form in a file is asked about (carry as text, or leave out),
 * never decided in silence.
 *
 * SQLite always runs; Postgres runs with TEST_POSTGRES_URL, MySQL with
 * TEST_MYSQL_URL (`./app-install-harness.ts`).
 */
import { parseEnumCheck } from '@adminium/engine';
import { validateManifest } from '@adminium/manifest';
import { optionListsRepo, overridesRepo, permissionsRepo, rolesRepo } from '@adminium/meta';
import { afterEach, describe, expect, it } from 'vitest';

import { findInstanceIds } from '../src/project/instance-ids.js';
import { ENGINES, installHarness, type Dialect, type Harness } from './app-install-harness.js';
import { asFile, latestModel, made, override, save, shapeOf, tableId } from './app-save-source.js';

type Doc = Record<string, unknown>;
type Column = { ref: string; type: string; nullable?: boolean; enum?: string[]; references?: string; relation?: Doc; rules?: Doc; label?: unknown; unique?: boolean; maxLength?: number; hidden?: boolean };
type Table = { ref: string; columns: Column[]; label?: unknown; labelPlural?: unknown; keyField?: string; indexes?: string[][] };

/** A shop's two tables, as each engine spells them. */
function shopTables(dialect: Dialect): string[] {
  if (dialect === 'postgres') {
    return [
      `CREATE TABLE customers (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name varchar(80) NOT NULL, email varchar(120) UNIQUE, status varchar(16) NOT NULL DEFAULT 'lead' CHECK (status IN ('lead', 'active')), notes text, created_at timestamptz DEFAULT now())`,
      `CREATE TABLE orders (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, customer_id integer NOT NULL REFERENCES customers (id), referrer_id integer, placed_on date, total decimal(10,2) NOT NULL DEFAULT 0, paid boolean NOT NULL DEFAULT false, size varchar(16))`,
      `CREATE INDEX orders_placed_on ON orders (placed_on)`,
    ];
  }
  if (dialect === 'mysql') {
    return [
      `CREATE TABLE customers (id int AUTO_INCREMENT PRIMARY KEY, name varchar(80) NOT NULL, email varchar(120) UNIQUE, status varchar(16) NOT NULL DEFAULT 'lead' CHECK (status IN ('lead', 'active')), notes text, created_at datetime DEFAULT CURRENT_TIMESTAMP)`,
      `CREATE TABLE orders (id int AUTO_INCREMENT PRIMARY KEY, customer_id int NOT NULL, referrer_id int, placed_on date, total decimal(10,2) NOT NULL DEFAULT 0, paid tinyint(1) NOT NULL DEFAULT 0, size varchar(16), CONSTRAINT orders_customer FOREIGN KEY (customer_id) REFERENCES customers (id))`,
      `CREATE INDEX orders_placed_on ON orders (placed_on)`,
    ];
  }
  return [
    `CREATE TABLE customers (id integer PRIMARY KEY, name varchar(80) NOT NULL, email varchar(120) UNIQUE, status varchar(16) NOT NULL DEFAULT 'lead' CHECK (status IN ('lead', 'active')), notes text, created_at timestamp DEFAULT CURRENT_TIMESTAMP)`,
    `CREATE TABLE orders (id integer PRIMARY KEY, customer_id integer NOT NULL REFERENCES customers (id), referrer_id integer, placed_on date, total decimal(10,2) NOT NULL DEFAULT 0, paid boolean NOT NULL DEFAULT 0, size varchar(16))`,
    `CREATE INDEX orders_placed_on ON orders (placed_on)`,
  ];
}

/** What a person does to them in Adminium. */
async function personChanges(h: Harness): Promise<void> {
  await override(h, 'customers', 'table.label', { label: { en_US: 'Customer', de_DE: 'Kunde' }, labelPlural: { en_US: 'Customers', de_DE: 'Kunden' }, icon: 'users' });
  await override(h, 'customers', 'table.keyField', { column: 'name' });
  await override(h, 'customers', 'column.label', { label: { en_US: 'Full name', fr_FR: 'Nom' } }, 'name');
  await override(h, 'customers', 'column.hidden', { hidden: true }, 'notes');
  await override(h, 'customers', 'column.enumLabels', { labels: { lead: 'Lead', active: { en_US: 'Active', de_DE: 'Aktiv' } } }, 'status');
  // The engine's own guess, never undone: it travels.
  await override(h, 'customers', 'column.pii', { masked: true, kind: 'email' }, 'email', 'auto');
  // A link a person added: there is no foreign key behind it.
  await override(h, 'orders', 'relation.add', { fromColumn: 'referrer_id', toTable: await tableId(h, 'customers'), toColumn: 'id', cardinality: 'many-to-one' });
  await override(h, 'orders', 'relation.label', { fromColumn: 'customer_id', label: 'Buyer' });
  await override(h, 'orders', 'column.validation', { min: 0 }, 'total');
  await optionListsRepo(h.meta).create({ key: 'shirt-sizes', name: 'Shirt sizes', items: [{ value: 'S', label: 'Small' }, { value: 'M', description: 'The usual one' }] });
  await override(h, 'orders', 'column.options', { list: 'shirt-sizes' }, 'size');
}

const tablesOf = (manifest: Doc): Table[] => (manifest['requiredSchema'] as { tables: Table[] }).tables;
const columnOf = (manifest: Doc, table: string, column: string): Column => tablesOf(manifest).find((one) => one.ref === table)!.columns.find((one) => one.ref === column)!;

let open: Harness[] = [];
afterEach(async () => {
  for (const h of open) await h.close();
  open = [];
});

async function harness(dialect: Dialect): Promise<Harness> {
  const h = await installHarness(dialect);
  open.push(h);
  return h;
}

for (const [dialect, available] of ENGINES) {
  describe.skipIf(!available)(`saving tables — ${dialect}`, () => {
    it('writes the tables and the person\'s words, and installs them the same on a fresh database', async () => {
      const h = await harness(dialect);
      await made(h, shopTables(dialect));
      await personChanges(h);
      const saved = await save(h, dialect);
      const { manifest, files } = asFile(saved);

      // The file: valid, and no id of this install in it.
      const valid = validateManifest(manifest, { allowLocalPublisher: true });
      expect(valid.ok, JSON.stringify(valid.ok ? [] : valid.issues)).toBe(true);
      expect(findInstanceIds(manifest)).toEqual([]);
      const text = JSON.stringify(manifest);
      expect(text).not.toContain(h.connectionId);
      expect(text).not.toContain('connectionId');
      expect(saved.check.filter((item) => item.group === 'choice')).toEqual([]);

      // What it says of each column.
      expect(columnOf(manifest, 'customers', 'id')).toMatchObject({ type: 'int', role: 'pk' });
      expect(columnOf(manifest, 'customers', 'id').nullable).toBeUndefined();
      expect(columnOf(manifest, 'customers', 'name')).toEqual({ ref: 'name', type: 'text', maxLength: 80, label: { 'en-US': 'Full name', 'fr-FR': 'Nom' } });
      expect(columnOf(manifest, 'customers', 'email')).toMatchObject({ type: 'text', maxLength: 120, nullable: true, unique: true, rules: { personal: true } });
      expect(columnOf(manifest, 'customers', 'status')).toMatchObject({ type: 'enum', enum: ['lead', 'active'], default: 'lead', rules: { enumLabels: { labels: { lead: 'Lead', active: { 'en-US': 'Active', 'de-DE': 'Aktiv' } } } } });
      expect(columnOf(manifest, 'customers', 'status').nullable).toBeUndefined();
      expect(columnOf(manifest, 'customers', 'notes')).toEqual({ ref: 'notes', type: 'text', nullable: true, hidden: true });
      expect(columnOf(manifest, 'orders', 'customer_id')).toEqual({ ref: 'customer_id', type: 'fk', references: 'customers', relation: { label: 'Buyer' } });
      expect(columnOf(manifest, 'orders', 'referrer_id')).toEqual({ ref: 'referrer_id', type: 'fk', references: 'customers', nullable: true, relation: { constraint: false } });
      expect(columnOf(manifest, 'orders', 'total')).toMatchObject({ type: 'decimal', default: 0, rules: { validation: { min: 0 } } });
      expect(columnOf(manifest, 'orders', 'size')).toEqual({ ref: 'size', type: 'text', maxLength: 16, nullable: true, rules: { options: { list: 'shirt-sizes' } } });
      const customers = tablesOf(manifest).find((one) => one.ref === 'customers')!;
      expect(customers).toMatchObject({ label: { 'en-US': 'Customer', 'de-DE': 'Kunde' }, labelPlural: { 'en-US': 'Customers', 'de-DE': 'Kunden' }, keyField: 'name' });
      expect(tablesOf(manifest).find((one) => one.ref === 'orders')!.indexes).toEqual([['placed_on']]);
      expect(manifest['optionLists']).toEqual({ 'shirt-sizes': { label: 'Shirt sizes', values: [{ value: 'S', label: 'Small' }, { value: 'M', description: 'The usual one' }] } });

      // Installed on a fresh database: the same tables, and the person's words with them.
      const before = shapeOf(await latestModel(h), ['customers', 'orders']);
      const target = await harness(dialect);
      const installed = await target.install(manifest, {}, files);
      expect(installed.statusCode, installed.body).toBe(200);
      expect(shapeOf(await latestModel(target), ['customers', 'orders'])).toEqual(before);
      const rules = (await overridesRepo(target.meta).listForConnection(target.connectionId, { status: 'active' })).map((row) => [row.op, row.columnName ?? row.value['fromColumn'] ?? '', row.value]);
      expect(rules).toContainEqual(['table.label', '', { label: { en_US: 'Customer', de_DE: 'Kunde' }, labelPlural: { en_US: 'Customers', de_DE: 'Kunden' } }]);
      expect(rules).toContainEqual(['column.pii', 'email', { masked: true }]);
      expect(rules).toContainEqual(['column.options', 'size', { list: 'shop-shirt-sizes' }]);
      expect(rules).toContainEqual(['relation.add', 'referrer_id', expect.objectContaining({ fromColumn: 'referrer_id', toColumn: 'id' })]);
      expect(rules).toContainEqual(['relation.label', 'customer_id', { fromColumn: 'customer_id', label: 'Buyer' }]);
      expect((await optionListsRepo(target.meta).findByKey('shop-shirt-sizes'))?.items).toEqual([{ value: 'S', label: 'Small' }, { value: 'M', description: 'The usual one' }]);
    });

    it('plans no change at all installed back onto the database it was saved from, using its tables', async () => {
      const h = await harness(dialect);
      await made(h, shopTables(dialect));
      await personChanges(h);
      const { manifest, files } = asFile(await save(h, dialect));
      await h.stage(manifest, files);
      const plan = await h.inject({ method: 'POST', url: '/apps/plan', payload: { key: 'shop', version: '1.0.0', connectionId: h.connectionId, existing: 'use' } });
      expect(plan.statusCode, plan.body).toBe(200);
      const planned = (JSON.parse(plan.body) as { plan: { installable: boolean; problems: unknown[]; tables: { ref: string; action: string; edits: unknown[] }[] } }).plan;
      expect(planned.problems).toEqual([]);
      expect(planned.installable).toBe(true);
      expect(planned.tables.map((table) => [table.ref, table.action, table.edits]).sort()).toEqual([
        ['customers', 'reuse', []],
        ['orders', 'reuse', []],
      ]);
    });

    it('asks about a column with no form in a file, and acts on the answer', async () => {
      const h = await harness(dialect);
      const key = dialect === 'mysql' ? 'id int AUTO_INCREMENT PRIMARY KEY' : dialect === 'postgres' ? 'id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' : 'id integer PRIMARY KEY';
      await made(h, [`CREATE TABLE gauges (${key}, reading decimal(14,6), label varchar(20))`, `CREATE TABLE pairs (a integer NOT NULL, b integer NOT NULL, note text, PRIMARY KEY (a, b))`]);
      const gauges = await tableId(h, 'gauges');
      const pairs = await tableId(h, 'pairs');

      const asked = await save(h, dialect);
      const choices = asked.check.filter((item) => item.group === 'choice');
      expect(choices).toEqual([
        expect.objectContaining({ code: 'TYPE_NO_FORM', kind: 'column', item: 'gauges', field: 'reading', answer: { choices: ['carry-as-text', 'leave-out'], target: `${gauges}.reading` } }),
        expect.objectContaining({ code: 'COMPOSITE_KEY', kind: 'table', item: 'pairs', answer: { choices: ['carry-as-text', 'leave-out'], target: pairs } }),
      ]);
      // Unanswered, the column is not written: nothing is decided for the person.
      expect(tablesOf(asked.manifest as unknown as Doc).find((one) => one.ref === 'gauges')!.columns.map((column) => column.ref)).toEqual(['id', 'label']);

      const carried = await save(h, dialect, { carryAsText: [`${gauges}.reading`, pairs] });
      expect(carried.check.filter((item) => item.group === 'choice')).toEqual([]);
      const doc = carried.manifest as unknown as Doc;
      expect(columnOf(doc, 'gauges', 'reading')).toEqual({ ref: 'reading', type: 'text', nullable: true });
      expect(tablesOf(doc).find((one) => one.ref === 'pairs')).toMatchObject({ unique: [['a', 'b']] });
      expect(columnOf(doc, 'pairs', 'a')).toEqual({ ref: 'a', type: 'int' });
      expect(validateManifest(asFile(carried).manifest, { allowLocalPublisher: true }).ok).toBe(true);

      const leftOut = await save(h, dialect, { leaveOut: [`column:${gauges}.reading`], tables: [gauges] });
      expect(leftOut.check.filter((item) => item.group === 'choice')).toEqual([]);
      expect(tablesOf(leftOut.manifest as unknown as Doc).map((table) => table.columns.map((column) => column.ref))).toEqual([['id', 'label']]);
    });

    it('names a link to a table that is not in the file, and keeps the column plain', async () => {
      const h = await harness(dialect);
      await made(h, shopTables(dialect));
      const saved = await save(h, dialect, { tables: [await tableId(h, 'orders')] });
      expect(columnOf(saved.manifest as unknown as Doc, 'orders', 'customer_id')).toEqual({ ref: 'customer_id', type: 'int' });
      expect(saved.check).toContainEqual(expect.objectContaining({ group: 'info', code: 'LINK_TABLE_LEFT_OUT', item: 'orders', field: 'customer_id' }));
      expect(validateManifest(asFile(saved).manifest, { allowLocalPublisher: true }).ok).toBe(true);
    });
  });
}

describe.skipIf(!ENGINES[1]![1])('a native enum — postgres', () => {
  it('saves as an enum and is used as it is: no change planned onto the source', async () => {
    const h = await harness('postgres');
    await made(h, [`CREATE TYPE mood AS ENUM ('calm', 'busy', 'closed')`, `CREATE TABLE days (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, mood mood NOT NULL DEFAULT 'calm', note text)`]);
    const { manifest, files } = asFile(await save(h, 'postgres'));
    expect(columnOf(manifest, 'days', 'mood')).toEqual({ ref: 'mood', type: 'enum', enum: ['calm', 'busy', 'closed'], default: 'calm' });
    await h.stage(manifest, files);
    const plan = await h.inject({ method: 'POST', url: '/apps/plan', payload: { key: 'shop', version: '1.0.0', connectionId: h.connectionId, existing: 'use' } });
    const planned = (JSON.parse(plan.body) as { plan: { installable: boolean; problems: unknown[]; tables: { ref: string; action: string; edits: unknown[] }[] } }).plan;
    expect(planned.problems).toEqual([]);
    expect(planned.tables.map((table) => [table.ref, table.action, table.edits])).toEqual([['days', 'reuse', []]]);

    // A fresh database gets the same choices, kept by a CHECK instead of a type of its own.
    const target = await harness('postgres');
    const installed = await target.install(manifest, {}, files);
    expect(installed.statusCode, installed.body).toBe(200);
    const days = (await latestModel(target)).tables.find((table) => table.name === 'days')!;
    const checked = days.checks.map((check) => parseEnumCheck(check.expression, days.columns.map((one) => one.name))).find((found) => found?.column === 'mood');
    expect(checked?.values).toEqual(['calm', 'busy', 'closed']);
  });

  it('asks about the types a file has no form for', async () => {
    const h = await harness('postgres');
    await made(h, [`CREATE TABLE visits (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, took interval, tags text[], seen_from inet)`]);
    const saved = await save(h, 'postgres');
    expect(saved.check.filter((item) => item.group === 'choice').map((item) => [item.code, item.field])).toEqual([
      ['TYPE_NO_FORM', 'took'],
      ['TYPE_NO_FORM', 'tags'],
      ['TYPE_NO_FORM', 'seen_from'],
    ]);
    expect(tablesOf(saved.manifest as unknown as Doc)[0]!.columns.map((column) => column.ref)).toEqual(['id']);
  });
});

describe('rules that name tables and roles', () => {
  it('names tables by their refs and roles by their keys, and says what does not travel', async () => {
    const h = await harness('sqlite');
    await made(h, [
      `CREATE TABLE customers (id integer PRIMARY KEY, name varchar(80) NOT NULL, spent decimal(10,2))`,
      `CREATE TABLE orders (id integer PRIMARY KEY, customer_id integer NOT NULL REFERENCES customers (id), total decimal(10,2) NOT NULL, ref varchar(16) UNIQUE, status varchar(16) NOT NULL DEFAULT 'new' CHECK (status IN ('new', 'sent', 'paid')))`,
      `CREATE TABLE notes (id integer PRIMARY KEY, code varchar(16), order_id integer REFERENCES orders (id))`,
    ]);
    const orders = await tableId(h, 'orders');
    const clerk = await rolesRepo(h.meta).create({ slug: 'clerk', name: 'Clerk' });
    const outsider = await rolesRepo(h.meta).create({ slug: 'outsider', name: 'Outsider' });
    for (const role of [clerk, outsider]) await permissionsRepo(h.meta).grant(role.id, 'table', `${h.connectionId}/${orders}`, { read: true, create: false, update: false, delete: false, export: false, import: false } as never);
    await override(h, 'customers', 'column.rollup', { from: orders, via: 'customer_id', sum: 'total' }, 'spent');
    await override(h, 'customers', 'column.copy', { via: 'missing_link', from: 'name' }, 'name');
    await override(h, 'orders', 'table.states', {
      column: 'status',
      initial: 'new',
      moves: { new: [{ to: 'sent', roles: ['clerk'] }], sent: [{ to: 'paid', roles: ['clerk', 'outsider'] }, { to: 'new', roles: ['outsider'] }] },
    });
    await override(h, 'orders', 'column.normalize', { normalize: 'code' }, 'ref');
    await override(h, 'notes', 'column.lookup', { from: 'code', table: orders, column: 'ref' }, 'order_id');

    // Only the clerk travels; the notes table does not.
    const saved = await save(h, 'sqlite', { roles: [clerk.id], tables: [await tableId(h, 'customers'), orders] });
    const doc = saved.manifest as unknown as Doc;
    expect(JSON.stringify(doc)).not.toContain(orders);
    expect(columnOf(doc, 'customers', 'spent').rules).toEqual({ rollup: { from: 'orders', via: 'customer_id', sum: 'total' } });
    expect(tablesOf(doc).find((table) => table.ref === 'orders')).toMatchObject({
      states: { column: 'status', initial: 'new', moves: { new: [{ to: 'sent', roles: ['clerk'] }], sent: [{ to: 'paid', roles: ['clerk'] }] } },
    });
    expect(saved.check).toContainEqual(expect.objectContaining({ group: 'info', code: 'STATE_ROLE_NOT_CARRIED', item: 'orders' }));
    // A copy through a link the table does not have is the validator's to refuse: taken off, and said.
    expect(columnOf(doc, 'customers', 'name').rules).toBeUndefined();
    expect(saved.check).toContainEqual(expect.objectContaining({ group: 'info', code: 'RULE_NOT_CARRIED', item: 'customers', field: 'name' }));

    // With the notes table: its lookup names orders by its ref.
    const all = await save(h, 'sqlite', { roles: [clerk.id] });
    expect(all.check.filter((item) => item.item === 'notes')).toEqual([]);
    expect(columnOf(all.manifest as unknown as Doc, 'notes', 'order_id').rules).toEqual({ lookup: { from: 'code', table: 'orders', column: 'ref' } });
  });
});
