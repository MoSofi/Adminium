/**
 * The words the kit's parts carry to an app's own screens, one file per
 * language: `src/kit-host/words/<tag>.ts`.
 *
 * A part mounted on an app's screen has no dashboard around it, so it cannot
 * read the dashboard's catalogues. `src/kit-host/words/keys.json` names, part
 * by part, the keys that part's code asks for; this script reads each of them
 * out of `packages/i18n/locales/<tag>/` and writes them down, so the build
 * makes a small chunk per language and a mount loads only its own.
 *
 * Run it after adding a key to `keys.json` or changing one of those texts:
 * `node scripts/gen-kit-words.mjs`. `src/kit-host/words.test.ts` fails while
 * the files and the catalogues disagree. `--check` writes nothing and exits 1
 * on a difference.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const wordsDir = join(root, 'src', 'kit-host', 'words');
const localesDir = join(root, '..', '..', 'packages', 'i18n', 'locales');

export const KIT_LOCALES = ['en-US', 'ar-EG', 'cs-CZ', 'da-DK', 'de-DE', 'fr-FR', 'zh-CN', 'zh-TW'];

const catalogues = new Map();
function catalogue(tag, ns) {
  const at = `${tag}/${ns}`;
  if (!catalogues.has(at)) catalogues.set(at, JSON.parse(readFileSync(join(localesDir, tag, `${ns}.json`), 'utf8')));
  return catalogues.get(at);
}

/** The text of `ns:a.b.c` in a language, or undefined. */
function textOf(tag, key) {
  const [ns, path] = key.split(':');
  let node = catalogue(tag, ns);
  for (const step of path.split('.')) {
    if (typeof node !== 'object' || node === null) return undefined;
    node = node[step];
  }
  return typeof node === 'string' ? node : undefined;
}

/** One language's file, as text. */
export function kitWordsFile(tag) {
  const keys = JSON.parse(readFileSync(join(wordsDir, 'keys.json'), 'utf8'));
  const out = {};
  for (const [part, list] of Object.entries(keys)) {
    out[part] = {};
    for (const key of list) {
      const text = textOf(tag, key);
      if (text === undefined) throw new Error(`gen-kit-words: ${tag} has no text for ${key} (part "${part}")`);
      out[part][key] = text;
    }
  }
  return [
    '// SPDX-License-Identifier: AGPL-3.0-only',
    '// GENERATED by scripts/gen-kit-words.mjs from words/keys.json and packages/i18n/locales. Do not edit.',
    "import type { KitWords } from '../contract.js';",
    '',
    `const words: KitWords = ${JSON.stringify(out, null, 2)};`,
    '',
    'export default words;',
    '',
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  let stale = 0;
  for (const tag of KIT_LOCALES) {
    const file = join(wordsDir, `${tag}.ts`);
    const next = kitWordsFile(tag);
    let now = '';
    try {
      now = readFileSync(file, 'utf8');
    } catch {
      // Not written yet.
    }
    if (now === next) continue;
    stale += 1;
    if (check) console.error(`gen-kit-words: ${tag}.ts is out of date`);
    else writeFileSync(file, next);
  }
  if (check && stale > 0) process.exit(1);
  console.log(check ? 'gen-kit-words: OK' : `gen-kit-words: ${String(stale)} file(s) written`);
}
